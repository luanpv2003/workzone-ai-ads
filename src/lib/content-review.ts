// Content approval → run ads: the user provides posts (link / pick from Page) or text + uploaded images / videos
// → Claude checks Meta policy + Vietnam Advertising Law → rollout plan (revised per feedback, multiple versions) → finalize → draft.
// No step publishes to Meta: the draft still goes through the editor and the Publish button (always PAUSED) like every other campaign.

export type Media = { url: string; rel?: string }; // rel: image stored on the server (data/uploads), url: for display
export type ContentItem = {
  id: string;
  source: "post" | "manual";
  postId: string | null; // {pageId}_{postId} when it is a Page post
  pageId: string | null;
  permalink: string | null;
  message: string;
  kind: "photo" | "album" | "video" | "text" | "link";
  images: Media[];
  frames: Media[]; // video frames (pre-generated by Meta, or extracted by the browser from uploaded video)
  videoSeconds: number | null;
  eligible: boolean | null; // Meta allows advertising this post (Page posts only)
  stats: { reactions: number | null; comments: number | null; shares: number | null } | null;
  created: string | null;
};
export type ReviewBrief = { goal: CampaignBrief["goal"]; dailyBudget: number; locations: string; ageMin: number; ageMax: number; landingUrl?: string; notes?: string };
export type PlanVersion = { at: string; feedback: string | null; data: ContentPlan & { plan_notes?: string[] }; model: string };

export const parseItems = (s: string): ContentItem[] => JSON.parse(s || "[]");
export const parsePlans = (s: string): PlanVersion[] => JSON.parse(s || "[]");

function fromPost(p: PostDetail): ContentItem {
  const kind = p.video ? "video" : p.images.length > 1 ? "album" : p.images.length ? "photo" : /link|share/.test(p.type) ? "link" : "text";
  return {
    id: randomUUID(),
    source: "post",
    postId: p.id,
    pageId: p.pageId,
    permalink: p.permalink,
    message: p.message,
    kind,
    images: (p.video ? p.images.slice(0, 1) : p.images).map((url) => ({ url })),
    frames: (p.video?.frames ?? []).map((url) => ({ url })),
    videoSeconds: p.video?.seconds ?? null,
    eligible: p.eligible,
    stats: { reactions: p.reactions, comments: p.comments, shares: p.shares },
    created: p.created,
  };
}

async function load(reviewId: string) {
  const r = await db.contentReview.findUniqueOrThrow({ where: { id: reviewId }, include: { client: true } });
  return { review: r, client: r.client, items: parseItems(r.items) };
}

async function saveItems(reviewId: string, items: ContentItem[]) {
  // Changing content invalidates old check results: return to the check step (keeping plan versions for review).
  await db.contentReview.update({ where: { id: reviewId }, data: { items: JSON.stringify(items), status: "new", policy: null, error: null } });
}

export async function createReview(clientId: string, title: string) {
  const r = await db.contentReview.create({ data: { clientId, title: title.trim() || (await getT())("targeting.contentLib.defaultTitle", { date: new Date().toLocaleDateString("vi-VN") }) } });
  return r.id;
}

/** Add posts from Facebook links. Returns unreadable links with reasons. */
export async function addLinks(reviewId: string, links: string[]) {
  const { client, items } = await load(reviewId);
  if (client.dataSource !== "meta") throw new Error((await getT())("targeting.contentLib.notConnected"));
  const meta = getMetaClient(client);
  const pageIds = clientPages(client).map((p) => p.id);
  const failed: { link: string; error: string }[] = [];
  for (const link of links.map((l) => l.trim()).filter(Boolean)) {
    try {
      const id = await meta.resolvePostLink(link, pageIds);
      if (!id) throw new Error((await getT())("targeting.contentLib.postNotFound"));
      if (items.some((i) => i.postId === id)) continue;
      items.push(fromPost(await meta.postDetail(id)));
    } catch (err) {
      failed.push({ link, error: err instanceof Error ? err.message : String(err) });
    }
  }
  await saveItems(reviewId, items);
  return failed;
}

export async function addPosts(reviewId: string, postIds: string[]) {
  const { client, items } = await load(reviewId);
  const meta = getMetaClient(client);
  // Only posts of this client's own Pages (the token may also see other clients' Pages).
  const pageIds = clientPages(client).map((p) => p.id);
  if (postIds.some((id) => !pageIds.includes(String(id).split("_")[0]))) throw new Error((await getT())("customers.actions.postNotOwned"));
  for (const id of postIds) if (!items.some((i) => i.postId === id)) items.push(fromPost(await meta.postDetail(id)));
  await saveItems(reviewId, items);
}

/** Unpublished content: text + uploaded images (+ frames the browser extracted from video). */
export async function addManual(reviewId: string, input: { message: string; images: string[]; frames: string[]; videoSeconds: number | null }) {
  const { items } = await load(reviewId);
  if (!input.message.trim() && !input.images.length && !input.frames.length) throw new Error((await getT())("targeting.contentLib.needContent"));
  const media = (rels: string[]) => rels.map((rel) => ({ rel, url: uploadUrl(rel) }));
  items.push({
    id: randomUUID(),
    source: "manual",
    postId: null,
    pageId: null,
    permalink: null,
    message: input.message.trim(),
    kind: input.frames.length ? "video" : input.images.length > 1 ? "album" : input.images.length ? "photo" : "text",
    images: media(input.images),
    frames: media(input.frames),
    videoSeconds: input.videoSeconds,
    eligible: null,
    stats: null,
    created: null,
  });
  await saveItems(reviewId, items);
}

export async function removeItem(reviewId: string, itemId: string) {
  const { items } = await load(reviewId);
  await saveItems(
    reviewId,
    items.filter((i) => i.id !== itemId),
  );
}

