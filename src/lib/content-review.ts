async function imageOf(m: Media, name: string): Promise<ImageInput | null> {
  try {
    let data: Buffer;
    let type: string;
    if (m.rel) {
      data = readFileSync(uploadFilePath(m.rel));
      type = m.rel.endsWith(".png") ? "image/png" : m.rel.endsWith(".webp") ? "image/webp" : "image/jpeg";
    } else {
      const res = await fetch(m.url);
      if (!res.ok) return null;
      type = (res.headers.get("content-type") ?? "").split(";")[0];
      data = Buffer.from(await res.arrayBuffer());
    }
    if (data.length > 4_000_000 || !/^image\/(jpeg|png|webp|gif)$/.test(type)) return null;
    // File extension by image type: Claude's Read tool needs the extension to open the image.
    return { name: `${name}.${type.split("/")[1].replace("jpeg", "jpg")}`, data, mediaType: type as ImageInput["mediaType"] };
  } catch {
    return null;
  }
}

/** Describe each content item for Claude + images / frames (at most 4 images and 4 frames per item, 20 images per batch). */
async function contentSection(items: ContentItem[]) {
  const images: ImageInput[] = [];
  const lines: string[] = [];
  for (const [i, it] of items.entries()) {
    const names: string[] = [];
    for (const [j, m] of it.images.slice(0, 4).entries()) {
      if (images.length >= 20) break;
      const img = await imageOf(m, `nd${i}_anh${j + 1}`);
      if (img) {
        images.push(img);
        names.push(img.name);
      }
    }
    const frames: string[] = [];
    for (const [j, m] of it.frames.slice(0, 4).entries()) {
      if (images.length >= 20) break;
      const img = await imageOf(m, `nd${i}_khung${j + 1}`);
      if (img) {
        images.push(img);
        frames.push(img.name);
      }
    }
    lines.push(
      [
        `## Content ${i} — ${it.source === "post" ? `post published on the Page (${it.kind})` : `unpublished (${it.kind})`}`,
        it.source === "post" && `Meta allows this post to be advertised: ${it.eligible === false ? "NO" : "yes"}`,
        it.stats && `Organic engagement: ${it.stats.reactions ?? "?"} reactions · ${it.stats.comments ?? "?"} comments · ${it.stats.shares ?? "?"} shares`,
        it.kind === "video" && `Video${it.videoSeconds ? ` ${Math.round(it.videoSeconds)} seconds` : ""}: you only see the frames ${frames.join(", ") || "(could not be extracted)"}; you CANNOT hear the audio (the video may contain music / speech; the user must listen to it themselves)`,
        names.length && `Images: ${names.join(", ")}`,
        `Text:\n"""\n${it.message || "(no text)"}\n"""`,
      ]
        .filter(Boolean)
        .join("\n"),
    );
  }
  return { text: lines.join("\n\n"), images };
}

export async function runPolicyCheck(reviewId: string) {
  const { client, items } = await load(reviewId);
  if (!items.length) throw new Error((await getT())("targeting.contentLib.nothingToCheck"));
  await db.contentReview.update({ where: { id: reviewId }, data: { status: "checking", error: null } });
  try {
    const { text, images } = await contentSection(items);
    const prompt = `# Client\n${clientProfile(client)}\n\n${await knowledgePromptSection(client.id)}\n\n# Content to check (${items.length})\n${text}\n\nCheck each content item.`;
    const res = await generateStructured({ clientId: client.id, system: POLICY_SYSTEM, prompt, schema: PolicyCheckSchema, effort: "high", images });
    await db.contentReview.update({ where: { id: reviewId }, data: { status: "checked", policy: JSON.stringify(res.data) } });
    const bad = res.data.items.filter((x) => x.verdict !== "safe").length;
    await logActivity(client.id, "analyze", (await getT())("targeting.contentLib.logPolicy", { n: items.length, result: bad ? (await getT())("targeting.contentLib.logPolicyBad", { bad }) : (await getT())("targeting.contentLib.logPolicyOk") }));
  } catch (err) {
    await db.contentReview.update({ where: { id: reviewId }, data: { status: "failed", error: err instanceof Error ? err.message : String(err) } });
    throw err;
  }
}

const VERDICT: Record<string, string> = { safe: "Safe", fix: "Needs fixing", reject: "Likely to be rejected" };

export function briefFor(review: { title: string; brief: string | null }, items: ContentItem[], client: { primaryResult: string; maxDailyBudget: number | null; currency: string }): CampaignBrief {
  const b: Partial<ReviewBrief> = review.brief ? JSON.parse(review.brief) : {};
  return CampaignBriefSchema.parse({
    product: `${review.title}. Run ads for ${items.length} content items: ${items.map((i, n) => `[${n}] ${i.message.replace(/\s+/g, " ").slice(0, 80) || i.kind}`).join(" | ")}`,
    goal: b.goal ?? client.primaryResult,
    dailyBudget: b.dailyBudget ?? client.maxDailyBudget ?? defaultDailyBudget(client.currency),
    locations: b.locations ?? "",
    ageMin: b.ageMin ?? 18,
    ageMax: b.ageMax ?? 65,
    ...(b.landingUrl && { landingUrl: b.landingUrl }),
    notes: b.notes,
  });
}

/** Draft the plan (feedback = feedback on the latest version; null = first version). */
export async function runContentPlan(reviewId: string, feedback: string | null) {
  const { review, client, items } = await load(reviewId);
  if (!review.policy) throw new Error((await getT())("targeting.contentLib.needPolicy"));
  const policy: PolicyCheck = JSON.parse(review.policy);
  const plans = parsePlans(review.plans);
  await db.contentReview.update({ where: { id: reviewId }, data: { status: "planning", error: null } });
  try {
    const brief = briefFor(review, items, client);
    const { text } = await contentSection(items.map((i) => ({ ...i, images: [], frames: [] }))); // images already viewed in the check step
    const prev = plans.at(-1);
    const history = plans
      .filter((p) => p.feedback)
      .map((p, i) => `- Round ${i + 1}: ${p.feedback}`)
      .join("\n");
    const prompt = `${await planPrompt(client.id, brief)}

# Content the user wants to run
${text}

# Policy check results
${policy.items
  .map((x) => `- Content ${x.index}: ${VERDICT[x.verdict]} — ${x.summary}${x.issues.length ? `\n  Issues: ${x.issues.map((i) => `[${i.severity}] ${i.policy}: "${i.quote}" → ${i.fix}`).join("; ")}` : ""}${x.rewrite ? `\n  Fixed version: ${JSON.stringify(x.rewrite)}` : ""}${x.special_category !== "none" ? `\n  Special ad category: ${x.special_category}` : ""}`)
  .join("\n")}
${prev ? `\n# Current plan (version ${plans.length})\n${JSON.stringify(prev.data)}\n` : ""}${history ? `\n# Previous user feedback\n${history}\n` : ""}${feedback ? `\n# User feedback (LATEST; follow it)\n${feedback}\n` : ""}
Draw up an ad plan for the content above.`;
    const res = await generateStructured({ clientId: client.id, system: `${PLANNER_SYSTEM}\n\n${CONTENT_PLAN_RULES}`, prompt, schema: ContentPlanSchema, effort: "high" });
    // Targeting items Claude proposed outside the list → search on Meta (so the plan shows real item names).
    const resolved = await resolvePlanTargeting(res.data.plan);
    const data = { ...res.data, plan: resolved.plan, plan_notes: resolved.notes };
    plans.push({ at: new Date().toISOString(), feedback, data, model: res.model });
    await db.contentReview.update({ where: { id: reviewId }, data: { status: "planned", plans: JSON.stringify(plans) } });
    await logActivity(client.id, "analyze", (await getT())("targeting.contentLib.logPlan", { version: plans.length > 1 ? " " + (await getT())("targeting.contentLib.logPlanVersion", { n: plans.length }) : "", title: review.title }));
  } catch (err) {
    await db.contentReview.update({ where: { id: reviewId }, data: { status: review.policy ? "checked" : "failed", error: err instanceof Error ? err.message : String(err) } });
    throw err;
  }
}

/** Finalize a version → campaign draft (attach existing posts / revised images + text to each ad). Returns the draft id. */
export async function finalizeReview(reviewId: string, version: number) {
  const { review, client, items } = await load(reviewId);
  const v = parsePlans(review.plans)[version];
  if (!v) throw new Error((await getT())("targeting.contentLib.versionNotFound"));
  if (review.draftId) {
    const d = await db.campaignDraft.findUnique({ where: { id: review.draftId }, select: { status: true } });
    if (d) throw new Error((await getT())("targeting.contentLib.alreadyFinal"));
  }
  const brief = briefFor(review, items, client);
  const use = new Map(v.data.content_use.map((u) => [u.index, u.use]));
  const ads = v.data.plan.ads.filter((a) => items[a.content_index] && use.get(a.content_index) !== "skip" && v.data.plan.ad_sets[a.ad_set_index]);
  if (!ads.length) throw new Error((await getT())("targeting.contentLib.noAds"));
  // Ad sets left without any ads (their content was dropped) are removed too, and ad set numbering is redone.
  const used = [...new Set(ads.map((a) => a.ad_set_index))].filter((i) => v.data.plan.ad_sets[i]).sort((a, b) => a - b);
  const remap = new Map(used.map((old, i) => [old, i]));
  const adSets = used.map((i) => v.data.plan.ad_sets[i]);
  const base = withEditorFields({ ...v.data.plan, ad_sets: adSets, ads: ads.filter((a) => remap.has(a.ad_set_index)).map((a) => ({ ad_set_index: remap.get(a.ad_set_index)!, name: a.name, primary_text: a.primary_text, headline: a.headline, description: a.description, call_to_action: a.call_to_action, creative_brief: a.creative_brief, existing_post_id: "" })) }, brief);
  const folder = `rv_${review.id}`;
  const pages = new Set<string>();
  for (const [i, a] of base.ads.entries()) {
    const it = items[ads[i].content_index];
    const existing = use.get(ads[i].content_index) === "existing" && it.postId && it.eligible !== false;
    if (existing) {
      pages.add(it.pageId!);
      Object.assign(a, {
        source: "existing",
        post_id: it.postId,
        post_preview: { message: it.message, picture: it.images[0]?.url ?? it.frames[0]?.url ?? null, permalink: it.permalink ?? "", type: it.kind, created: it.created ?? "" },
      });
    } else {
      // New ads: take the content's first image (Page images are downloaded to the server for publishing to Meta).
      const m = it.images[0];
      let rel = m?.rel ?? null;
      if (m && !rel) {
        try {
          const res = await fetch(m.url);
          if (res.ok) rel = saveUploadBuffer(folder, Buffer.from(await res.arrayBuffer()), await getT());
        } catch {}
      }
      Object.assign(a, { source: "new", image_path: rel });
    }
  }
  const pageId = pages.size === 1 ? [...pages][0] : null;
  const { plan, notes } = normalizePlan(enforceTargetingRules({ ...base, page_id: pageId && pageId !== client.metaPageId ? pageId : base.page_id }, await getT()), {
    t: await getT(),
    maxTotal: brief.dailyBudget,
    userGeo: true,
  });
  if (pages.size > 1) notes.push((await getT())("targeting.contentLib.multiPage"));
  const draft = await db.campaignDraft.create({
    data: { clientId: client.id, brief: JSON.stringify({ ...brief, source: "content_review", reviewId }), plan: JSON.stringify(plan), result: notes.length ? JSON.stringify({ notes }) : null },
  });
  await db.contentReview.update({ where: { id: reviewId }, data: { status: "final", chosen: version, draftId: draft.id } });
  await logActivity(client.id, "analyze", (await getT())("targeting.contentLib.logFinal", { version: version + 1, title: review.title, draft: plan.campaign_name }));
  await queueDraftPolicyCheck(client.id, draft.id, null); // text revised by Claude per the plan: re-check the final version
  return draft.id;
}

/** Self-setup without Claude: an empty draft pre-attached with the content (existing posts / images + text) as ads. */
export async function manualDraft(reviewId: string) {
  const { review, client, items } = await load(reviewId);
  if (!items.length) throw new Error((await getT())("targeting.contentLib.noContent"));
  const plan = blankPlan(client, await getT());
  const tpl = plan.ads[0];
  plan.ads = items
    .filter((it) => !(it.source === "manual" && it.kind === "video"))
    .map((it, i) => ({
      ...tpl,
      ad_set_index: 0,
      name: `${review.title} · ${i + 1}`,
      primary_text: it.message,
      ...(it.postId && it.eligible !== false
        ? { source: "existing" as const, post_id: it.postId, post_preview: { message: it.message, picture: it.images[0]?.url ?? null, permalink: it.permalink ?? "", type: it.kind, created: it.created ?? "" } }
        : { source: "new" as const, image_path: it.images[0]?.rel ?? null }),
    }));
  const draft = await db.campaignDraft.create({ data: { clientId: client.id, brief: JSON.stringify({ source: "content_review", reviewId }), plan: JSON.stringify(plan) } });
  await db.contentReview.update({ where: { id: reviewId }, data: { status: "final", draftId: draft.id } });
  return draft.id;
}

/** After publishing: Meta's actual review status for each ad of the draft. */
export async function reviewAdStatus(reviewId: string): Promise<{ published: boolean; ads: AdReview[]; error?: string }> {
  const { review, client } = await load(reviewId);
  if (!review.draftId) return { published: false, ads: [] };
  const d = await db.campaignDraft.findUnique({ where: { id: review.draftId } });
  if (d?.status !== "published" || !d.result) return { published: false, ads: [] };
  const ids = (JSON.parse(d.result) as { adIds?: string[] }).adIds ?? [];
  try {
    return { published: true, ads: await getMetaClient(client).adReviews(ids) };
  } catch (err) {
    return { published: true, ads: [], error: err instanceof Error ? err.message : String(err) };
  }
}
